// ---------- Company Income Tax Exemption Checker ----------
const TURNOVER_THRESHOLD = 100000000; // ₦100 million
const FIXED_ASSETS_THRESHOLD = 250000000; // ₦250 million

const naira = (n) => '₦' + (Number(n) || 0).toLocaleString('en-NG');

function computeStatus(turnover, fixedAssets) {
  const exempt = turnover <= TURNOVER_THRESHOLD && fixedAssets <= FIXED_ASSETS_THRESHOLD;
  return {
    exempt,
    items: [
      { title: 'Company Income Tax (CIT)', meta: exempt ? 'Exempt' : 'Applies' },
      { title: 'Capital Gains Tax (CGT)', meta: exempt ? 'Exempt' : 'Applies' },
      { title: '4% Development Levy', meta: exempt ? 'Exempt' : 'Applies' },
      { title: 'VAT', meta: 'Applies regardless of turnover' },
      { title: 'PAYE (if you have staff)', meta: 'Applies regardless of turnover' },
    ],
  };
}

let currentResult = null;

function render() {
  const turnover = Number(document.getElementById('turnover').value) || 0;
  const fixedAssets = Number(document.getElementById('fixedAssets').value) || 0;
  currentResult = { turnover, fixedAssets, ...computeStatus(turnover, fixedAssets) };

  const verdictWrap = document.getElementById('verdictWrap');
  const list = document.getElementById('tecList');

  if (!document.getElementById('turnover').value && !document.getElementById('fixedAssets').value) {
    verdictWrap.innerHTML = '';
    list.innerHTML = '<p style="font-size:0.86rem; opacity:0.55; padding:20px 0; text-align:center;">Enter your turnover and fixed assets to check your status.</p>';
    return;
  }

  verdictWrap.innerHTML = currentResult.exempt
    ? '<div class="tec-verdict exempt">You likely qualify for the small-company exemption.</div>'
    : '<div class="tec-verdict not-exempt">You likely do not qualify for the small-company exemption.</div>';

  list.innerHTML = currentResult.items.map(item => `
    <div class="cc-item">
      <div>
        <div class="cc-title">${item.title}</div>
      </div>
      <div class="cc-date">${item.meta}</div>
    </div>
  `).join('');
}

function buildPdfDoc() {
  const rows = currentResult.items.map(i => [i.title, i.meta]);
  return window.KoboExport.buildTablePdf({
    docLabel: 'Tax Exemption Check',
    businessName: 'My Business',
    businessSub: 'Generated by KoboDocs — kobodocs.com.ng/tax-exemption-checker',
    metaLines: [`Turnover: ${naira(currentResult.turnover)}`, `Fixed assets: ${naira(currentResult.fixedAssets)}`],
    columns: ['Obligation', 'Status'],
    rows,
    note: 'Based on the 2026 Tax Reform Acts small-company exemption threshold (₦100m turnover, ₦250m fixed assets). Estimate only, not tax advice — confirm with an accountant.',
  });
}

document.addEventListener('DOMContentLoaded', () => {
  ['turnover', 'fixedAssets'].forEach(id => {
    document.getElementById(id).addEventListener('input', render);
  });
  render();

  document.getElementById('downloadBtn').addEventListener('click', () => {
    if (!currentResult) return;
    window.KoboExport.download('tax-exemption-check.pdf', buildPdfDoc());
  });

  document.getElementById('shareBtn').addEventListener('click', () => {
    if (!currentResult) return;
    window.KoboExport.shareWhatsApp('tax-exemption-check.pdf', 'My business tax exemption check, made free with KoboDocs: https://kobodocs.com.ng/tax-exemption-checker/', buildPdfDoc());
  });
});
