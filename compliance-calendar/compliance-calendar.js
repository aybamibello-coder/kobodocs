// ---------- Free Compliance Calendar Generator ----------
const fmtDate = (d) => d.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });

function nextMonthly(day) {
  const now = new Date();
  const d = new Date(now.getFullYear(), now.getMonth() + (now.getDate() > day ? 1 : 0), day);
  return d;
}

function nextAnnual(month, day) {
  const now = new Date();
  let year = now.getFullYear();
  const candidate = new Date(year, month, day);
  if (candidate < now) year += 1;
  return new Date(year, month, day);
}

const INDUSTRY_EXTRAS = {
  manufacturing: [{ title: 'SON product/facility certification renewal', meta: 'Annual, varies by product category' }],
  food: [{ title: 'NAFDAC registration/renewal', meta: 'Annual — required for packaged food products' }],
  healthcare: [{ title: 'NAFDAC registration/renewal', meta: 'Annual — required for regulated health products' }],
  hotel: [{ title: 'State hospitality/tourism board permit renewal', meta: 'Annual, varies by state' }],
  construction: [{ title: 'State building/contractor permit renewal', meta: 'Annual, varies by state' }],
  professional: [{ title: 'Professional body license renewal', meta: 'Annual — e.g. ICAN, NBA, COREN, depending on your field' }],
  ngo: [{ title: 'SCUML registration/compliance', meta: 'Required for NGOs and designated non-financial businesses' }],
  logistics: [{ title: 'Vehicle roadworthiness & operating permit renewal', meta: 'Annual, varies by state' }],
  school: [{ title: 'State Ministry of Education operating permit renewal', meta: 'Annual, varies by state' }],
  general: [],
};

function buildChecklist(bizType, hasStaff, incorpMonth) {
  const items = [];
  const annualMonth = incorpMonth !== '' && incorpMonth !== null ? parseInt(incorpMonth, 10) : 11; // default Dec if unknown

  items.push({ title: 'VAT filing (FIRS)', meta: 'Monthly, by the 21st', date: nextMonthly(21) });
  items.push({ title: 'CAC Annual Return', meta: 'Annual' + (incorpMonth === '' ? ' — based on your incorporation anniversary' : ''), date: nextAnnual(annualMonth, 28) });
  items.push({ title: 'Company Income Tax filing (FIRS)', meta: 'Annual, within 6 months of your financial year end', date: nextAnnual(5, 30) });
  items.push({ title: 'Business premises/permit renewal', meta: 'Annual, varies by state/LGA', date: nextAnnual(0, 31) });

  if (hasStaff === 'yes') {
    items.push({ title: 'PAYE remittance', meta: 'Monthly, by the 10th', date: nextMonthly(10) });
    items.push({ title: 'Pension remittance (PenCom)', meta: 'Monthly, by the 7th', date: nextMonthly(7) });
    items.push({ title: 'NSITF contribution', meta: 'Annual — employee compensation scheme', date: nextAnnual(2, 31) });
    items.push({ title: 'ITF contribution', meta: 'Annual — if you have 5+ employees', date: nextAnnual(3, 1) });
    items.push({ title: 'NHF remittance', meta: 'Monthly, where applicable', date: nextMonthly(10) });
  }

  (INDUSTRY_EXTRAS[bizType] || []).forEach(extra => {
    items.push({ ...extra, date: nextAnnual(annualMonth, 28) });
  });

  return items.sort((a, b) => a.date - b.date);
}

let currentChecklist = [];

function renderChecklist() {
  const bizType = document.getElementById('bizType').value;
  const hasStaff = document.getElementById('hasStaff').value;
  const incorpMonth = document.getElementById('incorpMonth').value;
  currentChecklist = buildChecklist(bizType, hasStaff, incorpMonth);

  const list = document.getElementById('ccList');
  if (!currentChecklist.length) {
    list.innerHTML = '<div class="cc-empty">No obligations to show.</div>';
    return;
  }
  list.innerHTML = currentChecklist.map(item => `
    <div class="cc-item">
      <div>
        <div class="cc-title">${item.title}</div>
        <div class="cc-meta">${item.meta}</div>
      </div>
      <div class="cc-date">${fmtDate(item.date)}</div>
    </div>
  `).join('');
}

function buildPdfDoc() {
  return window.KoboExport.buildTablePdf({
    docLabel: 'Compliance Calendar',
    businessName: 'My Business',
    businessSub: 'Generated by KoboDocs — kobodocs.com.ng/compliance-calendar',
    columns: ['Obligation', 'Details', 'Next due'],
    rows: currentChecklist.map(i => [i.title, i.meta, fmtDate(i.date)]),
    note: 'Estimates based on common Nigerian business requirements — not legal or tax advice. Confirm specifics with your accountant.',
  });
}

document.addEventListener('DOMContentLoaded', () => {
  ['bizType', 'hasStaff', 'incorpMonth'].forEach(id => {
    document.getElementById(id).addEventListener('change', renderChecklist);
  });

  renderChecklist();

  document.getElementById('downloadBtn').addEventListener('click', () => {
    if (!currentChecklist.length) return;
    window.KoboExport.download('compliance-calendar.pdf', buildPdfDoc());
  });

  document.getElementById('shareBtn').addEventListener('click', () => {
    if (!currentChecklist.length) return;
    window.KoboExport.shareWhatsApp('compliance-calendar.pdf', 'My business compliance calendar, made free with KoboDocs: https://kobodocs.com.ng/compliance-calendar/', buildPdfDoc());
  });
});
